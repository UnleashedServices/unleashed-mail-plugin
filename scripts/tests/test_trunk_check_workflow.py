def _excluded_entries(literal: str) -> frozenset:
    """The ENTRY SET of a `--filter=-a,-b` literal. Any other shape is refused, never coerced."""
    prefix = "--filter="
    if not literal.startswith(prefix) or any(c.isspace() for c in literal):
        raise ValueError(f"{literal!r} is not a single `--filter=` argument")
    entries = literal[len(prefix) :].split(",")
    if not all(entry.startswith("-") and len(entry) > 1 for entry in entries):
        raise ValueError(f"{literal!r} has an entry that is not a `-name` exclusion")
    return frozenset(entry[1:] for entry in entries)


def exclusion_problems(required: str, canary: str, enabled: frozenset) -> list:
    """Cell 4 (COREDEV-2850): the required job's exclusion is a frozen SET, nothing security-bearing is
    in it, and it differs from the canary's by EXACTLY the five formatters, in both directions.

    A substring test is what this replaces: `assertIn("markdown-link-check", literal)` is satisfied
    by a seven-name literal, by a security exclusion, and by an issue-code suppression alike.
    """
    try:
        req = _excluded_entries(required)
        can = _excluded_entries(canary)
    except ValueError as error:
        return [f"exclusion: malformed literal — {error}"]
    problems = []
    if req != EXCLUDED_LINTERS:
        problems.append(
            "exclusion: the required job's excluded set is not exactly the six declared entries"
        )
    if required == canary:
        problems.append("exclusion: the required and canary literals are identical")
    if req - can != THE_FIVE_FORMATTERS or can - req:
        problems.append(
            "exclusion: required and canary differ by something other than exactly the five "
            "formatters"
        )
    # `--filter` accepts ISSUE CODES as well as names and does NOT validate codes, so
    # `-bandit/B602` would silently suppress a security rule that a name-set check cannot see.
    if any("/" in entry for entry in req | can):
        problems.append(
            "exclusion: an excluded entry is an issue code, not a linter name"
        )
    if (req | can) & SECURITY_LINTERS:
        problems.append("exclusion: a security linter is excluded")
    # `--filter` validates NAMES against `lint.enabled` and aborts with EXIT 2 — an argument error,
    # not a lint failure — and dropping a formatter from `lint.enabled` is a plausible follow-up edit
    # precisely because it no longer runs here.
    if (req | can) - enabled:
        problems.append(
            "exclusion: an excluded name is not in `lint.enabled` (trunk aborts with EXIT 2)"
        )
    return problems


def contract_problems(
    workflow: dict, *, milestone: str = "M2", entry: str = "required"
) -> list[str]:
    """§1's contract, clause by clause, as diagnostics. Cell 11 mutates against THIS.

    ONE implementation for BOTH entries. C0, C3-C9 and C6a are identical for the required workflow and
    the canary — the plan's own answer to two comparators drifting — and the two places they genuinely
    differ are branched on explicitly rather than forked into a second copy:

      * the EVENT (C1/C2's `pull_request` with its `types:` widening, versus the canary's `on: push`);
      * `continue-on-error`, which is M2's temporary JOB-scoped exemption on the required workflow and
        a PERMANENT, REQUIRED, job-scoped obligation on the canary.
    """
    is_canary = entry == "canary"
    problems: list[str] = []
    on = _on(workflow)
    job = _job(workflow)
    steps = _steps(workflow)
    names = [step.get("name") for step in steps]

    # C0 — the workflow ROOT mapping is an allowlist, and `permissions` is pinned BY VALUE.
    problems.extend(
        f"root mapping: unlisted key `{key}`"
        for key in sorted(_root_keys(workflow) - {"name", "on", "permissions", "jobs"})
    )
    if workflow.get("permissions") != {"contents": "read"}:
        problems.append(
            f"root permissions: expected `contents: read`, found {workflow.get('permissions')!r}"
        )
    if "concurrency" in workflow:
        problems.append("workflow-level `concurrency` is prohibited")
    if "concurrency" in job:
        problems.append("job-level `concurrency` is prohibited")

    # C1 / C7 — one event, and its options are an allowlist.
    expected_event = "push" if is_canary else "pull_request"
    problems.extend(
        (
            "event set: `merge_group` is prohibited (check_mode=none is a false success)"
            if event == "merge_group"
            else f"event set: unlisted event `{event}`"
        )
        for event in sorted(set(on) - {expected_event})
    )
    if expected_event not in on:
        problems.append(f"event set: `{expected_event}` is absent")
    elif is_canary:
        problems.extend(
            f"push options: unlisted option `{option}`"
            for option in sorted(set(on["push"] or {}) - {"branches"})
        )
        if "branches" not in on["push"]:
            problems.append("branches: key is absent")
    else:
        problems.extend(
            (
                f"pull_request options: unlisted option `{option}`"
                if option not in ("paths", "paths-ignore")
                else f"pull_request options: `{option}` narrows reachability"
            )
            for option in sorted(set(on["pull_request"] or {}) - {"branches", "types"})
        )
        # C2 — branches, and the activity set.
        if "branches" not in on["pull_request"]:
            problems.append("branches: key is absent")
        if "types" not in on["pull_request"]:
            problems.append("types: key is absent")
        else:
            types = on["pull_request"]["types"]
            types = set(types) if isinstance(types, list) else {types}
            if "edited" not in types:
                problems.append("types: `edited` is missing from the activity set")
            # C2 states the set EXACTLY. Checking only for `edited` let `types: [edited]` pass, which
            # drops `synchronize`, so the gate never re-runs on a new commit (codex, r44).
            if types != EXPECTED_PR_TYPES:
                problems.append(
                    "types: the activity set is not exactly `opened, synchronize, reopened, edited`"
                )

    # C3 — the EFFECTIVE context is pinned. `name:` decides which status context a job emits, so an
    # unconstrained `name` let the canary emit the REQUIRED `validate` context while its job ID, the
    # only thing checked, stayed `trunk-check-push` (codex, r46).
    expected_context = CANARY_CONTEXT if is_canary else EXPECTED_CONTEXT
    effective_context = str(job.get("name") or _job_id(workflow))
    if effective_context != expected_context:
        problems.append(
            f"job: effective context `{effective_context}` is not `{expected_context}`"
        )

    # C3 — the JOB mapping is an allowlist, and nothing skips or masks.
    allowed_job = {"runs-on", "timeout-minutes", "permissions", "steps", "name"}
    if is_canary or milestone == "M2":
        allowed_job |= M2_ADVISORY_EXEMPTION
    problems.extend(
        f"job mapping: unlisted key `{key}`" for key in sorted(set(job) - allowed_job)
    )
    if is_canary and job.get("continue-on-error") is not True:
        # REQUIRED-PRESENT and permanent here. Its failure mode is omission, and an absent key would
        # let the canary's failure fail the workflow run.
        problems.append("canary: job-scoped `continue-on-error` is absent")
    if job.get("permissions") != {"contents": "read"}:
        problems.append(
            f"job permissions: expected `contents: read`, found {job.get('permissions')!r}"
        )
    if "if" in job:
        problems.append("job: `if:` is prohibited (a skipped job reports Success)")
    if not is_canary and milestone != "M2" and job.get("continue-on-error"):
        problems.append("job: `continue-on-error:` is prohibited")
    if "defaults" in workflow:
        problems.append("workflow `defaults.run` is prohibited")
    if "defaults" in job:
        problems.append("job `defaults.run` is prohibited")
    if job.get("runs-on") != EXPECTED_RUNNER:
        problems.append(
            f"job: expected `runs-on: {EXPECTED_RUNNER}`, found {job.get('runs-on')!r}"
        )
    if job.get("timeout-minutes") != EXPECTED_TIMEOUT_MINUTES:
        problems.append(
            f"job: expected `timeout-minutes: {EXPECTED_TIMEOUT_MINUTES}`, "
            f"found {job.get('timeout-minutes')!r}"
        )

    invocations = sum(
        1
        for step in steps
        if ACTION_PIN.split("@", maxsplit=1)[0] in str(step.get("uses", ""))
    )
    if invocations != 1:
        problems.append(
            f"steps: expected exactly one Trunk invocation, found {invocations}"
        )

    # C8 — the step sequence is an allowlist, in order.
    if names != EXPECTED_STEPS:
        problems.extend(
            f"step sequence: `{expected}` is absent"
            for expected in EXPECTED_STEPS
            if expected not in names
        )
        problems.extend(
            "step sequence: unexpected step before `trunk`"
            for actual in names
            if actual not in EXPECTED_STEPS
        )
        if (
            sorted(filter(None, names)) == sorted(EXPECTED_STEPS)
            and names != EXPECTED_STEPS
        ):
            problems.append(
                "step sequence: `guard-launcher-path` is not immediately before `trunk`"
            )
        # A DUPLICATE known name escaped all three checks above (codex, r45). `_step()` reads only the
        # first occurrence, so a second checkout after the guards was never inspected at all.
        problems.extend(
            f"step sequence: `{name}` appears {names.count(name)} times"
            for name in EXPECTED_STEPS
            if names.count(name) > 1
        )
        # And whatever shape is left: ANY sequence unequal to the declared five is a problem, so no
        # future blind spot in the specific diagnostics above can turn into a pass.
        problems.append("step sequence: not exactly the five declared steps, in order")

    for step in steps:
        label = step.get("name")
        # C8 freezes the COMPLETE step mapping. This was a six-key blacklist, so any other key
        # (`timeout-minutes`, say) passed (codex, r44). Keys that change behaviour keep their
        # specific diagnostic; anything else is unlisted.
        allowed = RUN_STEP_KEYS if "run" in step else USES_STEP_KEYS
        problems.extend(
            (
                f"step `{label}`: `{key}:` is prohibited"
                if key in PROHIBITED_STEP_KEYS
                else f"step `{label}`: unlisted key `{key}`"
            )
            for key in sorted(set(step) - allowed)
        )
        body = step.get("run", "")
        if "GITHUB_ENV" in body:
            problems.append(f"step `{label}`: writes to $GITHUB_ENV")
        if "GITHUB_PATH" in body:
            problems.append(f"step `{label}`: writes to $GITHUB_PATH")
        # Only the C6 guard may NAME a launcher path; any other body mentioning one is planting it.
        # C6's guard inspects the tree once, so a body that creates a path is the hole the guard's
        # adjacency to the action exists to close, from inside a step the sequence allows.
        if label != "guard-launcher-path" and any(
            path in body for path in C6_GUARDED_PATHS
        ):
            problems.append(f"step `{label}`: creates a prohibited launcher path")
        frozen = EXPECTED_RUN_BODY_DIGESTS[entry].get(str(label))
        if (
            frozen is not None
            and hashlib.sha256(body.encode("utf-8")).hexdigest() != frozen
        ):
            problems.append(f"step `{label}`: run body digest mismatch")

    # C5 — no `env:` at workflow, job OR step scope.
    if "env" in workflow:
        problems.append("workflow-level `env:` is prohibited")
    if "env" in job:
        problems.append("job-level `env:` is prohibited")

    # C8 — checkout inputs are allowlisted too, with two REQUIRED-PRESENT members.
    if "checkout" in names:
        # C8: `actions/checkout` (SHA-pinned). Only its inputs were checked, so `@v4` passed (codex,
        # r44). The exact SHA is left to Dependabot; the FORM is what this contract freezes.
        if not re.fullmatch(
            r"actions/checkout@[0-9a-f]{40}",
            str(_step(workflow, "checkout").get("uses", "")),
        ):
            problems.append(
                "checkout: `uses` is not `actions/checkout` pinned by a full commit SHA"
            )
        checkout = _step(workflow, "checkout").get("with", {})
        for key in sorted(
            set(checkout) - {"fetch-depth", "lfs", "persist-credentials"}
        ):
            problems.append(f"checkout inputs: unlisted input `{key}`")  # noqa: PERF401
        if "lfs" not in checkout:
            problems.append("checkout inputs: `lfs` is absent")
        elif checkout["lfs"] is not True:
            problems.append("checkout inputs: `lfs` must be true")
        if "persist-credentials" not in checkout:
            problems.append("checkout inputs: `persist-credentials` is absent")
        elif checkout["persist-credentials"] is not False:
            problems.append("checkout inputs: `persist-credentials` must be false")

    # C4 / C9 — the action's inputs are an allowlist, and the action is pinned by exact SHA.
    if "trunk" in names:
        trunk = _step(workflow, "trunk")
        if trunk.get("uses") != ACTION_PIN:
            problems.append(
                "action pin: not pinned to the expected SHA"
                if "@" in str(trunk.get("uses"))
                and len(str(trunk.get("uses")).split("@")[-1]) == 40
                else "action pin: `trunk-io/trunk-action` is not pinned by SHA"
            )
        used = trunk.get("with", {})
        for key in sorted(
            set(used) - {"arguments", "save-annotations", "cache", "cache-key"}
        ):
            problems.append(f"action inputs: unlisted input `{key}`")  # noqa: PERF401
        if "arguments" not in used:
            problems.append("action inputs: `arguments` is absent")
        elif used["arguments"] != (
            CANARY_ARGUMENTS_LITERAL if is_canary else ARGUMENTS_LITERAL
        ):
            problems.append(
                "action inputs: `arguments` does not equal the declared literal"
            )
        if "save-annotations" not in used:
            problems.append("action inputs: `save-annotations` is absent")
        elif used["save-annotations"] is not True:
            problems.append("action inputs: `save-annotations` must be true")

    # C6 — the guard that runs last before the action must REFUSE by default rather than enumerate.
    #
    # This used to assert that every guarded path appeared as a LITERAL in the guard body, which is a
    # check on a spelling: it stayed green while `.trunk/user_trunk.yaml` — a path trunk merges and
    # the guard did not name — walked through. The enumeration was the defect, so asserting the
    # enumeration is complete cannot be the check. The property is now "anything under .trunk/ that
    # is not explicitly allowed is refused", and it is proved by executing the guard against a
    # fixture per path in `C6AndC6aGuardsExecuteAgainstFixtureTrees`, not by reading it.
    if "guard-launcher-path" in names:
        guard = _step(workflow, "guard-launcher-path").get("run", "")
        if "find .trunk" not in guard:
            problems.append(
                "C6 guard: does not enumerate the .trunk tree from the filesystem"
            )
        if ".trunk/configs/*" not in guard:
            problems.append(
                "C6 guard: has no allowlist for the configuration it legitimately ships"
            )

    return problems


