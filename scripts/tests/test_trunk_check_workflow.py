class C6AndC6aGuardsExecuteAgainstFixtureTrees(unittest.TestCase):
    """The remaining registry cases, run by EXECUTING THE SHIPPED GUARD BODIES.

    These are `repo_fixture` and `content_digest` kinds: they need a checked-out tree, so a parser
    cannot evaluate them. Rather than defer them to a real CI run, the guard's own bytes are lifted out
    of the workflow and run against a temporary tree — which tests what ships, not a reimplementation
    of it. A test that re-implements the guard proves the test correct, not the guard.
    """

    @classmethod
    def setUpClass(cls):
        workflow = _load_workflow()
        cls.c6_guard = _step(workflow, "guard-launcher-path")["run"]
        cls.c6a_guard = _step(workflow, "guard-resolver-digest")["run"]

    @staticmethod
    def _shimmed_path(tmp: Path) -> str:
        """`sha256sum` is GNU coreutils; the runner is ubuntu-latest but developers are not. Shim it
        onto PATH from `shasum` so the SHIPPED body runs unmodified on both."""
        import shutil

        if shutil.which("sha256sum"):
            return os.environ["PATH"]
        shim = tmp / "_shim"
        shim.mkdir(exist_ok=True)
        script = shim / "sha256sum"
        script.write_text('#!/bin/sh\nexec shasum -a 256 "$@"\n', encoding="utf-8")
        script.chmod(0o755)
        return f"{shim}:{os.environ['PATH']}"

    def _run(self, script: str, cwd: Path):
        return subprocess.run(
            ["bash", "-c", script],
            check=False,
            cwd=cwd,
            capture_output=True,
            text=True,
            env={"PATH": self._shimmed_path(cwd), "HOME": str(cwd)},
        )

    def test_the_c6_guard_passes_on_a_clean_tree(self):
        """The positive control: every case below must start from a guard that says yes."""
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(0, self._run(self.c6_guard, Path(tmp)).returncode)

    def test_each_guarded_path_is_caught_separately(self):
        """A guard that catches six of seven is a gate with one door open, so each is its own case.

        That is not hypothetical here: the seventh, `.trunk/user_trunk.yaml`, was the door left open,
        and it was open because the guard was an enumeration. Each path is executed against the real
        guard rather than grepped for.
        """
        for path in C6_GUARDED_PATHS:
            with self.subTest(fixture=path), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                # NOT `lstrip("./")` — that strips CHARACTERS, so `.trunk/bin/trunk` became
                # `trunk/bin/trunk` and the guard caught `./trunk` instead. The case still went
                # red, for the wrong path: reachability, not discrimination. Asserting the
                # specific path in stderr is what exposed it.
                relative = path.removeprefix("./")
                target = root / relative
                if path == ".trunk/setup-ci":
                    # MUST be a VALID composite action that exits green. `uses: ./.trunk/setup-ci`
                    # expects an action DIRECTORY, so a bare executable reds because it is
                    # MALFORMED — and would survive deletion of C6 while appearing to be caught.
                    target.mkdir(parents=True)
                    (target / "action.yml").write_text(
                        "name: setup-ci\nruns:\n  using: composite\n  steps:\n"
                        "    - run: 'true'\n      shell: bash\n",
                        encoding="utf-8",
                    )
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
                    target.chmod(0o755)
                completed = self._run(self.c6_guard, root)
                self.assertNotEqual(0, completed.returncode, f"{path} was not caught")
                self.assertIn(path, completed.stderr)

    def test_each_guarded_path_is_caught_AS_A_SYMLINK_TOO(self):
        """THE TYPE AXIS, which the path axis left open.

        Every fixture above is a REGULAR FILE, so the guard could enumerate with `find -type f` —
        which matches regular files only — and pass all seven while a committed symlink at the very
        same path walked through. The action's `locate_trunk.sh` tests `[[ -f ]] && [[ -x ]]`, and
        bash's file tests FOLLOW symlinks: the enumerator did not follow, the consumer did, and the
        gate reported success having linted nothing (codex, PR #84).

        Reverting the guard to `-type f` must make this red. Without it, the fix is unfalsifiable.
        """
        for path in C6_GUARDED_PATHS:
            with self.subTest(fixture=path), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                relative = path.removeprefix("./")
                target = root / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                # The symlink TARGET lives outside the guarded tree, which is the realistic shape:
                # a repository vendoring its own launcher and pointing at it.
                payload = root / "vendor" / "payload"
                payload.parent.mkdir(parents=True, exist_ok=True)
                if path == ".trunk/setup-ci":
                    payload.mkdir()
                    (payload / "action.yml").write_text(
                        "name: setup-ci\nruns:\n  using: composite\n  steps:\n"
                        "    - run: 'true'\n      shell: bash\n",
                        encoding="utf-8",
                    )
                else:
                    payload.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
                    payload.chmod(0o755)
                target.symlink_to(payload)
                completed = self._run(self.c6_guard, root)
                self.assertNotEqual(
                    0, completed.returncode, f"{path} as a SYMLINK was not caught"
                )
                self.assertIn(path, completed.stderr)

    def test_a_DANGLING_launcher_symlink_is_caught(self):
        """`-e` follows the link and is FALSE when the target does not exist, so a launcher pointing
        at something a later step creates was invisible. That is the other half of the same `run:`
        body, outside `.trunk/`, which the sweep fix does not reach."""
        for path in ("tools/trunk", "./trunk"):
            with self.subTest(fixture=path), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                target = root / path.removeprefix("./")
                target.parent.mkdir(parents=True, exist_ok=True)
                target.symlink_to(root / "not-created-yet")
                self.assertFalse(target.exists(), "the fixture must actually dangle")
                completed = self._run(self.c6_guard, root)
                self.assertNotEqual(
                    0, completed.returncode, f"a dangling {path} was not caught"
                )

    def test_the_c6a_guard_accepts_the_shipped_resolver_and_rejects_an_edited_one(self):
        """C6a.resolver-pinned-by-digest/edit-resolver — the invoking run bodies are left UNTOUCHED,
        which is exactly the hole C8's body digest cannot see."""
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "scripts/ci").mkdir(parents=True)
            target = root / "scripts/ci/resolve-trunk-range.sh"
            target.write_bytes(RESOLVER_PATH.read_bytes())
            self.assertEqual(
                0,
                self._run(self.c6a_guard, root).returncode,
                "the shipped resolver must satisfy its own pinned digest",
            )

            target.write_bytes(RESOLVER_PATH.read_bytes() + b"\necho tampered\n")
            completed = self._run(self.c6a_guard, root)
            self.assertNotEqual(0, completed.returncode)
            self.assertIn("digest mismatch", completed.stderr)

    def test_the_digest_guard_would_fire_before_the_resolver_ever_runs(self):
        """ "Verify, then execute" is the property C6a exists for. Under §0's threat model an edited
        resolver still fails closed at the C6 guard, but that is the wrong step reporting it.
        """
        names = [step.get("name") for step in _steps(_load_workflow())]
        self.assertLess(
            names.index("guard-resolver-digest"), names.index("guard-empty-diff")
        )


class TheRemoteReadsSurviveAMachineWithoutGh(unittest.TestCase):
    """`check=False` covers `gh` refusing. It does not cover `gh` being ABSENT.

    A missing binary raises FileNotFoundError out of the exec itself, so on any machine without the
    GitHub CLI this module would ERROR — not skip — and take the other 50-odd contract tests down
    with it at discovery time (gemini, PR #84). The remote halves were deliberately designed to
    return None and let their tests skip; an uncaught exec failure defeats that design entirely.

    Asserted by actually removing `gh` from PATH rather than by reading the source for a `try`.
    """

    @staticmethod
    def _sandbox_path(tmp: str) -> str:
        """A PATH with the interpreters these functions need and definitively no `gh`."""
        binaries = Path(tmp) / "bin"
        binaries.mkdir()
        for tool in ("python3", "sh", "bash", "env", "git"):
            for prefix in ("/usr/bin", "/bin", "/usr/local/bin", "/opt/homebrew/bin"):
                candidate = Path(prefix) / tool
                if candidate.exists():
                    (binaries / tool).symlink_to(candidate)
                    break
        return str(binaries)

    def _call_in_sandbox(self, function_name: str):
        with tempfile.TemporaryDirectory() as tmp:
            path = self._sandbox_path(tmp)
            self.assertIsNone(
                shutil.which("gh", path=path), "the sandbox must not offer gh"
            )
            program = (
                "import runpy, sys, json\n"
                f"module = runpy.run_path({str(MODULE_PATH)!r})\n"
                f"print(json.dumps(module[{function_name!r}]() is None))\n"
            )
            # ONLY `PATH` is replaced. Blanking the whole environment also strips the interpreter's
            # user site-packages, so the child failed on `import yaml` and the test would have
            # "passed" for a reason that had nothing to do with `gh`.
            return subprocess.run(
                [sys.executable, "-c", program],
                check=False,
                capture_output=True,
                text=True,
                env={**os.environ, "PATH": path},
                timeout=120,
            )

    def test_a_missing_gh_returns_None_rather_than_raising(self):
        for function_name in ("_live_ruleset", "_resolve_target_set"):
            with self.subTest(function=function_name):
                completed = self._call_in_sandbox(function_name)
                self.assertNotIn(
                    "FileNotFoundError",
                    completed.stderr,
                    "a machine without gh must not raise out of the remote read",
                )
                self.assertEqual(
                    0, completed.returncode, f"exec failed: {completed.stderr[-400:]}"
                )
                self.assertEqual(
                    "true",
                    completed.stdout.strip(),
                    "the remote read must report None so its assertions skip",
                )


