class Cell14_ExactlyOneProducerOfTheContext(unittest.TestCase):
    """Keying on the JOB ID alone is the wrong identifier: a job declared `jobs.other` with
    `name: trunk-check` produces exactly the same required context."""

    @staticmethod
    def _producers(workflows: dict[str, dict]) -> list[str]:
        found = []
        for path, workflow in workflows.items():
            for job_id, job in (workflow.get("jobs") or {}).items():
                explicit = job.get("name")
                if explicit is not None and not isinstance(explicit, str):
                    raise AssertionError(f"{path}: job {job_id} has a non-string name")
                if explicit and ("${{" in explicit):
                    # FAIL CLOSED: a static census cannot resolve an expression-valued name.
                    raise AssertionError(f"{path}: job {job_id} has an expression-valued name")
                if (explicit or job_id) == EXPECTED_CONTEXT:
                    found.append(f"{path}:{job_id}")
        return found

    def _tree(self) -> dict[str, dict]:
        return {p.name: yaml.safe_load(p.read_text(encoding="utf-8"))
                for p in sorted((REPO / ".github/workflows").glob("*.yml"))}

    def test_exactly_one_producer_repo_wide(self):
        self.assertEqual(["trunk-check.yml:trunk-check"], self._producers(self._tree()))

    def test_a_second_producer_under_a_different_job_id_is_detected(self):
        tree = self._tree()
        tree["decoy.yml"] = {"jobs": {"something-else": {"name": EXPECTED_CONTEXT}}}
        self.assertEqual(2, len(self._producers(tree)))

    def test_zero_producers_is_detected(self):
        self.assertEqual([], self._producers({"none.yml": {"jobs": {"other": {}}}}))

    def test_an_expression_valued_name_fails_closed(self):
        with self.assertRaises(AssertionError):
            self._producers({"x.yml": {"jobs": {"j": {"name": "${{ matrix.n }}"}}}})


