#!/usr/bin/env python3
"""COREDEV-2780 M2 — the trunk-check workflow against §1's contract.

Owns cells 4, 9, 14 and 15, cell 10's STATIC half, and cell 11's mutant generation.

WHY THE ORACLE IS FROZEN HERE AND NOT READ FROM THE TREE. The hazard this ticket exists to close is a
gate that reports green having checked nothing, and its most seductive form is an assertion that reads
its expectation out of the artifact under test: a silently reduced configuration then becomes
AUTHORITATIVE OVER THE ASSERTION MEANT TO DETECT IT. So the nineteen linter names, the runner, the
timeout, the action SHA and the argument literal are literals here.

WHAT CELL 11 DOES. It does not carry a hand-written mutant list — every earlier revision of this plan
had one and every round found a different member missing. Mutants are GENERATED by iterating the
mutation CASES in docs/planning/COREDEV-2780-contract.yaml, so under-coverage is impossible by
construction rather than by assertion. Each generated mutant must be CONSTRUCTIBLE, must change the
intended property, and must fail with ITS OWN diagnostic — a mutant killed through a sibling clause's
message proves reachability, not discrimination.
"""

